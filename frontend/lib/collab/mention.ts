/********************************************************
 파일명 : mention.ts (lib/collab)
 설 명 : 메시지에 `@AI` 멘션이 있는지 판정한다(이슈 #19). 협업방은 멘션이 있을 때만 AI가 답하므로
 (#13·#17 정책), 입력창이 "지금 이 문장은 AI를 부른다/부르지 않는다"를 미리 보여주는 데 쓴다.

 **판정의 주인은 서버다.** 확정 규칙은 #17에서 정해지고, 화면은 그 전에 사용자를 돕기 위한
 안내만 한다 — 여기서 참이라고 답이 보장되는 게 아니라, 여기서 거짓이면 부르지 않을 것이라는
 쪽이 사용자에게 중요한 정보다. 그래서 관대하게(대소문자 무시) 잡는다.
 *********************************************************/

/** 입력창 안내와 자동 삽입에 함께 쓰는 표기. 서버가 실제로 읽는 문자열과 같아야 한다. */
export const AI_MENTION = '@AI';

/**
 * 백엔드 AiMentionParser와 같은 경계 계약이다. 앞에는 유니코드 문자·숫자·밑줄이 올 수 없고,
 * 뒤에는 ASCII 식별자 문자가 올 수 없다. 한글 접미는 호칭으로 보아 허용한다.
 */
export function mentionsAi(content: string): boolean {
  return /(?<![\p{L}\p{N}_])@ai(?![A-Za-z0-9_])/iu.test(content);
}
